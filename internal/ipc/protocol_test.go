func TestCodecDoesNotAllocate(t *testing.T) {
	res := sampleResult()
	key := &Key{Ctx: 1, Seq: 2, Keysym: 'a'}
	buf := make([]byte, 0, 4096)
	var stream bytes.Buffer
	for i := 0; i < 4; i++ {
		stream.Write(res.Append(nil))
		stream.Write(key.Append(nil))
	}
	data := stream.Bytes()
	src := bytes.NewReader(data)
	r := NewReader(src, 4096)
	var dres Result
	var dkey Key
	dres.Candidates = make([]Candidate, 0, 16)
	n := testing.AllocsPerRun(1000, func() {
		buf = res.Append(buf[:0])
		buf = key.Append(buf)
		src.Reset(data)
		for i := 0; i < 8; i++ {
			typ, payload, err := r.Next()
			if err != nil {
				t.Fatal(err)
			}
			switch typ {
			case TypeResult:
				_ = dres.Decode(payload)
			case TypeKey:
				_ = dkey.Decode(payload)
			}
		}
	})
	if n != 0 {
		t.Fatalf("codec allocates %v times per round", n)
	}
}

func FuzzDecode(f *testing.F) {
	for _, v := range vectors() {
		f.Add(v.frame)
	}
	f.Fuzz(func(t *testing.T, b []byte) {
		r := NewReader(bytes.NewReader(b), 64)
		for {
			typ, payload, err := r.Next()
			if err != nil {
				return
			}
			var m interface{ Decode([]byte) error }
			switch typ {
			case TypeHello:
				m = &Hello{}
			case TypeWelcome:
				m = &Welcome{}
			case TypeKey:
				m = &Key{}
			case TypeFocusIn:
				m = &FocusIn{}
			case TypeFocusOut:
				m = &FocusOut{}
			case TypeCaret:
				m = &Caret{}
			case TypeSelect:
				m = &Select{}
			case TypeChangePage:
				m = &ChangePage{}
			case TypeClear:
				m = &Clear{}
			case TypeSetOption:
				m = &SetOption{}
			case TypeResult:
				m = &Result{}
			case TypeUnavailable:
				m = &Unavailable{}
			case TypeMigrate:
				m = &Migrate{}
			case TypePolicy:
				var p policy.Policy
				_ = DecodePolicy(payload, &p)
				continue
			default:
				continue
			}
			_ = m.Decode(payload)
		}
	})
}
