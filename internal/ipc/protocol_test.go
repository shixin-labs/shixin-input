func TestGolden(t *testing.T) {
	path := filepath.Join("testdata", "golden.txt")
	var b strings.Builder
	b.WriteString("# name hex-frame; generated by `go test ./internal/ipc -update`.\n")
	b.WriteString("# Frames only ever gain trailing fields. Never change an existing line.\n")
	for _, v := range vectors() {
		fmt.Fprintf(&b, "%s %s\n", v.name, hex.EncodeToString(v.frame))
	}
	if *update {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if b.String() != string(want) {
		t.Fatalf("encoding differs from %s; if the change is intended and append-only, run with -update\n got:\n%s", path, b.String())
	}
}

func TestRoundTrip(t *testing.T) {
	type decoder interface{ Decode([]byte) error }
	for _, c := range []struct {
		in, out decoder
		t       Type
	}{
		{&Hello{Version: 1, Kind: KindTSF, PID: 9, App: []byte("x.exe")}, &Hello{}, TypeHello},
		{&Welcome{Version: 1, Features: 5}, &Welcome{}, TypeWelcome},
		{&Key{Ctx: 1, Seq: 2, Keysym: 3, Mods: 4, Flags: 5}, &Key{}, TypeKey},
		{&FocusIn{Ctx: 1, Flags: 1, App: []byte("a")}, &FocusIn{}, TypeFocusIn},
		{&FocusOut{Ctx: 9}, &FocusOut{}, TypeFocusOut},
		{&Select{Ctx: 1, Seq: 2, Index: 3}, &Select{}, TypeSelect},
		{&ChangePage{Ctx: 1, Seq: 2, Backward: true}, &ChangePage{}, TypeChangePage},
		{&Clear{Ctx: 1, Seq: 2}, &Clear{}, TypeClear},
		{&SetOption{Ctx: 1, Seq: 2, On: true, Name: []byte("ascii_mode")}, &SetOption{}, TypeSetOption},
		{sampleResult(), &Result{}, TypeResult},
		{&Unavailable{Reason: 2}, &Unavailable{}, TypeUnavailable},
		{&Migrate{Endpoint: []byte("e")}, &Migrate{}, TypeMigrate},
		{&StatsRequest{Reset: true}, &StatsRequest{}, TypeStatsRequest},
		{sampleRerankStats(), &Stats{}, TypeStats},
		{&Caret{Ctx: 9, Left: -400, Top: 20, Right: -398, Bottom: 44}, &Caret{}, TypeCaret},
	} {
		frame := c.in.(interface{ Append([]byte) []byte }).Append(nil)
		r := NewReader(bytes.NewReader(frame), 64)
		typ, payload, err := r.Next()
		if err != nil || typ != c.t {
			t.Fatalf("%T: Next = %v, %v", c.in, typ, err)
		}
		if err := c.out.Decode(payload); err != nil {
			t.Fatalf("%T: %v", c.in, err)
		}
		if !reflect.DeepEqual(c.in, c.out) {
			t.Errorf("%T round trip:\n got %+v\nwant %+v", c.in, c.out, c.in)
		}
		// Truncated payloads are rejected, never misread. Stats without
		// the 智能排序 section are an older engine's, and valid.
		old := len(sampleStats().Append(nil)) - 5
		for i := 0; i < len(payload); i++ {
			if c.t == TypeStats && i == old {
				continue
			}
			if err := c.out.Decode(payload[:i]); err == nil {
				t.Errorf("%T: %d-byte prefix decoded", c.in, i)
			}
		}
		// Appended fields from a newer peer are ignored.
		if err := c.out.Decode(append(bytes.Clone(payload), 1, 2, 3)); err != nil {
			t.Errorf("%T with trailing bytes: %v", c.in, err)
		}
	}
	// An engine without 智能排序 sends no section.
	var st Stats
	st.Rerank = &RerankStats{}
	if err := st.Decode(sampleStats().Append(nil)[5:]); err != nil || st.Rerank != nil {
		t.Errorf("stats without 智能排序: %v, %+v", err, st.Rerank)
	}
	var p policy.Policy
	frame := AppendPolicy(nil, samplePolicy())
	if err := DecodePolicy(frame[5:], &p); err != nil || !reflect.DeepEqual(&p, samplePolicy()) {
		t.Errorf("policy round trip: %v %+v", err, p)
	}
}

// chunked returns at most n bytes per Read.
type chunked struct {
	r io.Reader
	n int
}

func (c chunked) Read(p []byte) (int, error) { return c.r.Read(p[:min(len(p), c.n)]) }

func TestReaderSplitsStream(t *testing.T) {
	var stream []byte
	var want []Type
	for i := 0; i < 50; i++ {
		res := sampleResult()
		res.Seq = uint32(i)
		res.Preedit = bytes.Repeat([]byte("a"), i*37) // exercises buffer growth
		stream = res.Append(stream)
		want = append(want, TypeResult)
		stream = (&Key{Seq: uint32(i)}).Append(stream)
		want = append(want, TypeKey)
	}
	for _, chunk := range []int{1, 3, 7, 64, 4096} {
		r := NewReader(chunked{bytes.NewReader(stream), chunk}, 16)
		for i, w := range want {
			typ, payload, err := r.Next()
			if err != nil || typ != w {
				t.Fatalf("chunk %d frame %d: %v %v", chunk, i, typ, err)
			}
			if typ == TypeResult {
				var res Result
				if err := res.Decode(payload); err != nil || res.Seq != uint32(i/2) || len(res.Preedit) != i/2*37 {
					t.Fatalf("chunk %d frame %d: %v seq %d", chunk, i, err, res.Seq)
				}
			}
		}
		if _, _, err := r.Next(); err != io.EOF {
			t.Fatalf("chunk %d: end = %v", chunk, err)
		}
	}
	r := NewReader(bytes.NewReader(stream[:len(stream)-1]), 16)
	var err error
	for err == nil {
		_, _, err = r.Next()
	}
	if err != io.ErrUnexpectedEOF {
		t.Fatalf("truncated stream: %v", err)
	}
}

