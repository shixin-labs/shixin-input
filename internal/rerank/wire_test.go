var update = flag.Bool("update", false, "rewrite testdata/golden.txt")

func sampleScore() *Score {
	return &Score{Session: 3, ExportSeq: 41, App: 2, AppRev: 7, Strength: StrengthStandard, Entries: []ScoreEntry{
		{Weight: -9.5, Text: []byte("台湾")},
		{Weight: -11.25, Flags: EntryUser, Text: []byte("太晚")},
		{Weight: 0, Flags: EntryFixed, Text: []byte("TW")},
	}}
}

func wireVectors() []struct {
	name  string
	frame []byte
} {
	return []struct {
		name  string
		frame []byte
	}{
		{"hello", (&Hello{Version: WireVersion}).Append(nil)},
		{"status", (&Status{Version: WireVersion, Ready: true}).Append(nil)},
		{"context", (&Context{App: 2, Rev: 7, Text: []byte("我们去")}).Append(nil)},
		{"score", sampleScore().Append(nil)},
		{"rerank", (&Rerank{Session: 3, ExportSeq: 41, Perm: []uint8{1, 0, 2}}).Append(nil)},
	}
}

func TestWireGolden(t *testing.T) {
	path := filepath.Join("testdata", "golden.txt")
	var b strings.Builder
	b.WriteString("# name hex-frame; generated by `go test ./internal/rerank -update`.\n")
	b.WriteString("# Frames only ever gain trailing fields. Never change an existing line.\n")
	for _, v := range wireVectors() {
		fmt.Fprintf(&b, "%s %s\n", v.name, hex.EncodeToString(v.frame))
	}
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if b.String() != string(want) {
		t.Fatalf("encoding differs from %s; if the change is intended and append-only, run with -update\n got:\n%s", path, b.String())
	}
}

func TestWireRoundTrip(t *testing.T) {
	type message interface {
		Append([]byte) []byte
		Decode([]byte) error
	}
	for _, c := range []struct {
		in, out message
		t       ipc.Type
	}{
		{&Hello{Version: 1}, &Hello{}, TypeHello},
		{&Status{Version: 1, Ready: true}, &Status{}, TypeStatus},
		{&Context{App: 1, Rev: 2, Text: []byte("文")}, &Context{}, TypeContext},
		{sampleScore(), &Score{}, TypeScore},
		{&Rerank{Session: 1, ExportSeq: 2, Perm: []uint8{2, 0, 1}}, &Rerank{}, TypeRerank},
	} {
		frame := c.in.Append(nil)
		typ, payload, err := ipc.NewReader(bytes.NewReader(frame), 64).Next()
		if err != nil || typ != c.t {
			t.Fatalf("%T: %v %v", c.in, typ, err)
		}
		if err := c.out.Decode(payload); err != nil || !reflect.DeepEqual(c.in, c.out) {
			t.Errorf("%T: %v\n got %+v\nwant %+v", c.in, err, c.out, c.in)
		}
		for i := range payload {
			if c.out.Decode(payload[:i]) == nil {
				t.Errorf("%T: %d-byte prefix decoded", c.in, i)
			}
		}
	}
}

func TestAppendScoreMatchesScore(t *testing.T) {
	var sl Slot
	want := sampleScore()
	used := 0
	for i, e := range want.Entries {
		copy(sl.Arena[used:], e.Text)
		sl.Entries[i] = Entry{Offset: uint16(used), Length: uint16(len(e.Text)), Flags: e.Flags, Weight: e.Weight}
		used += len(e.Text)
	}
	sl.Count, sl.ExportSeq = uint16(len(want.Entries)), want.ExportSeq
	req := Request{Session: int(want.Session), ExportSeq: want.ExportSeq, App: int(want.App), AppRev: want.AppRev, Export: &sl}
	if got := AppendScore(nil, &req, want.Strength); !bytes.Equal(got, want.Append(nil)) {
		t.Errorf("AppendScore differs:\n%x\n%x", got, want.Append(nil))
	}
	buf := make([]byte, 0, 8192)
	if a := testing.AllocsPerRun(100, func() { buf = AppendScore(buf[:0], &req, want.Strength) }); a != 0 {
		t.Errorf("AppendScore allocates %v times", a)
	}
}
