// Engine lists for rime-ice's pinyin schemas, without its lua_* components
// (DESIGN §3.8). Features that rime-ice implements in Lua come back as
// librime-shixin components (shixin_*), configured by rime-ice's own keys;
// the rest are absent. shixin_select_character comes after the recognizer
// so that keys it binds still reach a recognized input such as cC5-3.
//
// 智能排序 (DESIGN §7.2) is always listed and passes through while off:
// shixin_rerank_processor first, so no other processor sees the engine's
// private refresh key, and the shixin_rerank filter first, so it reorders
// librime's own simplified candidates before emoji, 繁体 and uniquifier.
var (
	processors  = []string{"shixin_rerank_processor", "ascii_composer", "recognizer", "shixin_select_character", "key_binder", "speller", "punctuator", "selector", "navigator", "express_editor"}
	segmentors  = []string{"ascii_segmentor", "matcher", "abc_segmentor", "affix_segmentor@radical_lookup", "punct_segmentor", "fallback_segmentor"}
	translators = []string{"punct_translator", "script_translator", "shixin_date_translator", "table_translator@custom_phrase",
		"table_translator@melt_eng", "table_translator@cn_en", "table_translator@radical_lookup",
		"shixin_unicode_translator", "shixin_number_translator", "shixin_calc_translator"}
	filters = []string{"shixin_rerank", "reverse_lookup_filter@radical_reverse_lookup", "simplifier@emoji", "simplifier@traditionalize", "uniquifier"}
)

// englishTranslators are left out without mixed English input.
var englishTranslators = map[string]bool{"table_translator@melt_eng": true, "table_translator@cn_en": true}

// PhraseTable is the custom phrase table the compiler writes; the schemas'
// custom_phrase translator reads <PhraseTable>.txt from the user dir.
const PhraseTable = "shixin_phrases"

const header = "# Generated by 拾新 from settings.json. Don't edit: changes are overwritten.\n" +
	"# Use the settings app instead.\n"

// shiftedDigits are the characters macOS reports for Shift+digit with
// Control held (charactersIgnoringModifiers keeps Shift), so a Rime binding
// such as Control+Shift+3 also needs Control+Shift+numbersign.
var shiftedDigits = map[byte]string{
	'1': "exclam", '2': "at", '3': "numbersign", '4': "dollar", '5': "percent",
	'6': "asciicircum", '7': "ampersand", '8': "asterisk", '9': "parenleft", '0': "parenright",
}

// keyVariants returns the Rime key names a shortcut must be bound as.
func keyVariants(key string) []string {
	if key == "" {
		return nil
	}
	out := []string{key}
	i := strings.LastIndexByte(key, '+')
	base, mods := key[i+1:], key[:i+1]
	if !strings.Contains(mods, "Shift+") || len(base) != 1 {
		return out
	}
	switch c := base[0]; {
	case shiftedDigits[c] != "":
		out = append(out, mods+shiftedDigits[c])
	case c >= 'A' && c <= 'Z':
		out = append(out, mods+string(c+'a'-'A'))
	}
	return out
}

// Compile returns the generated files for the Rime user dir, by name.
func Compile(s Settings) (map[string][]byte, error) {
	if err := s.Validate(); err != nil {
		return nil, err
	}
	files := map[string][]byte{}

	var d bytes.Buffer
	d.WriteString(header + "patch:\n")
	fmt.Fprintf(&d, "  schema_list:\n    - schema: %s\n", s.Scheme)
	fmt.Fprintf(&d, "  menu/page_size: %d\n", s.PageSize)
	shift := s.Shift
	if shift == "off" {
		shift = "noop"
	}
	// macOS handles Caps Lock itself (its own input source switching), so
	// Rime treats it as plain Caps Lock.
	for _, kv := range [][2]string{
		{"good_old_caps_lock", "true"},
		{"switch_key/Shift_L", shift},
		{"switch_key/Shift_R", shift},
		{"switch_key/Control_L", "noop"},
		{"switch_key/Control_R", "noop"},
		{"switch_key/Caps_Lock", "clear"},
		{"switch_key/Eisu_toggle", "clear"},
	} {
		fmt.Fprintf(&d, "  ascii_composer/%s: %s\n", kv[0], kv[1])
	}
	list(&d, "switcher/hotkeys", keyVariants(s.Hotkeys["switcher"]))
	// Settings decide each switch's initial state (below); librime's saved
	// options would override them.
	list(&d, "switcher/save_options", nil)
	files["default.custom.yaml"] = d.Bytes()

	for _, sc := range Schemes {
		var b bytes.Buffer
		b.WriteString(header + "patch:\n")
		list(&b, "engine/processors", processors)
		list(&b, "engine/segmentors", segmentors)
		var ts []string
		for _, t := range translators {
			if s.MixedEnglish || !englishTranslators[t] {
				ts = append(ts, t)
			}
		}
		list(&b, "engine/translators", ts)
		list(&b, "engine/filters", filters)
		// Keep emoji conversion for recognized input, but preserve the
		// native translators' exact readings (十 must not become 🔟).
		list(&b, "emoji/excluded_types", []string{"date", "number", "unicode", "calc"})
		// rime-ice shows each candidate's pinyin as its comment for its
		// corrector.lua, which Shixin doesn't run; Sogou shows none.
		b.WriteString("  translator/spelling_hints: 0\n  translator/always_show_comments: false\n  translator/comment_format: []\n")
		writeSwitches(&b, &s)
		writeKeyBinder(&b, &s)
		writeEditor(&b, &s)
		fmt.Fprintf(&b, "  custom_phrase/user_dict: %s\n", PhraseTable)
		writeSpeller(&b, &s, sc.ID)
		files[sc.ID+".custom.yaml"] = b.Bytes()
	}

	files[PhraseTable+".txt"] = phraseTable(s.Phrases)
	return files, nil
}

func writeSpeller(b *bytes.Buffer, s *Settings, scheme string) {
	var rules []string
	for _, f := range s.Fuzzy {
		rules = append(rules, fuzzyRules(f)...)
	}
	if scheme == "rime_ice" {
		if len(rules) > 0 {
			list(b, "speller/algebra/+", rules)
		}
		return
	}
	if s.FullPinyinFallback {
		// Freeze an additional full spelling in uppercase. The supported
		// layouts convert lowercase syllables (using circled capitals as
		// their own markers), leaving this branch untouched. Restore it
		// only after conversion. Don't revive the reserved xx spelling.
		rules = append(rules, `derive/^(?!xx$)([a-z]+)$/\U$1/`,
			`derive/^([NL])VE$/$1UE/`, `derive/^([JQXY])U/$1V/`,
			`derive/^([NL])UE$/$1VE/`, `derive/^([JQXY])V/$1U/`)
		list(b, "speller/algebra/+", []string{`xlit/ABCDEFGHIJKLMNOPQRSTUVWXYZ/abcdefghijklmnopqrstuvwxyz/`})
	}
	// Fuzzy syllables are derived before either spelling branch. librime
	// sorts patch keys lexically, so pad indices to retain their order.
	for i, rule := range rules {
		fmt.Fprintf(b, "  speller/algebra/@before %03d: %s\n", i, quote(rule))
	}
}

// writeEditor exposes forgetting through the editor's native action. Disable
// its inherited Ctrl+Delete binding unless selected, and prevent Shift+Delete
// from reaching it through the editor's Shift-as-Control fallback.
func writeEditor(b *bytes.Buffer, s *Settings) {
	key := s.Hotkeys["forget"]
	action := "noop"
	if key == "Control+Delete" {
		action = "delete_candidate"
	}
	fmt.Fprintf(b, "  editor/bindings:\n    Control+Delete: %s\n    Shift+Delete: delete\n", action)
	if key != "" && key != "Control+Delete" {
		fmt.Fprintf(b, "    %s: delete_candidate\n", quote(key))
	}
}

// writeSwitches writes rime-ice's switches with their initial states from
// the settings, without the ones only its Lua scripts use.
func writeSwitches(b *bytes.Buffer, s *Settings) {
	reset := func(on bool) int {
		if on {
			return 1
		}
		return 0
	}
	b.WriteString("  switches:\n")
	for _, sw := range []struct {
		name, states string
		reset        int
	}{
		{"ascii_mode", "[中, Ａ]", reset(s.InitialMode == ModeEnglish)},
		{"ascii_punct", "[¥, $]", reset(s.Punctuation == ModeEnglish)},
		{"traditionalization", "[简, 繁]", reset(s.Traditional)},
		{"emoji", "[💀, 😄]", reset(s.Emoji)},
		{"full_shape", "[半角, 全角]", 0},
	} {
		fmt.Fprintf(b, "    - {name: %s, states: %s, reset: %d}\n", sw.name, sw.states, sw.reset)
	}
}

// writeKeyBinder writes the whole key_binder map, replacing rime-ice's
// (and with it its import of default.yaml's bindings).
func writeKeyBinder(b *bytes.Buffer, s *Settings) {
	b.WriteString("  key_binder:\n")
	if keys, ok := KeyPair(s.SelectChar); ok {
		fmt.Fprintf(b, "    select_first_character: %s\n    select_last_character: %s\n", keys[0], keys[1])
	}
	b.WriteString("    bindings:\n")
	bind := func(when, accept, action string) {
		fmt.Fprintf(b, "      - {when: %s, accept: %s, %s}\n", when, quote(accept), action)
	}
	tabPages := false
	for _, k := range s.PageKeys {
		tabPages = tabPages || k == "tab"
	}
	if !tabPages {
		// Tab and Shift+Tab move the caret between syllables.
		bind("composing", "Shift+Tab", "send: Shift+Left")
		bind("composing", "Tab", "send: Shift+Right")
	}
	bind("composing", "Alt+Left", "send: Shift+Left")
	bind("composing", "Alt+Right", "send: Shift+Right")
	for _, id := range s.PageKeys {
		keys, _ := KeyPair(id)
		bind("has_menu", keys[0], "send: Page_Up")
		bind("has_menu", keys[1], "send: Page_Down")
	}
	if keys, ok := CandidateKeyPair(s.CandidateKeys); ok {
		// Control bypasses recognizer/speller handling of digits in native
		// number, Unicode and calculator input. Selector handles Ctrl+2/3
		// as indices on the current page; KeyBinder prevents recursion.
		bind("has_menu", keys[0], "send: Control+2")
		bind("has_menu", keys[1], "send: Control+3")
	}
	for _, a := range HotkeyActions {
		if a.Toggle == "" {
			continue
		}
		for _, k := range keyVariants(s.Hotkeys[a.ID]) {
			bind("always", k, "toggle: "+a.Toggle)
		}
	}
	// The keypad's digits select candidates like the main row's.
	for c := '0'; c <= '9'; c++ {
		bind("composing", "KP_"+string(c), "send: "+string(c))
	}
}

func phraseTable(ps []Phrase) []byte {
	var b bytes.Buffer
	// A Rime text table, as rime-ice's custom_phrase.txt: metadata
	// comments, then "text<TAB>code<TAB>weight" lines. Earlier phrases
	// come first.
	fmt.Fprintf(&b, "# Rime table\n# coding: utf-8\n#@/db_name\t%s.txt\n#@/db_type\ttabledb\n", PhraseTable)
	b.WriteString(header)
	for i, p := range ps {
		fmt.Fprintf(&b, "%s\t%s\t%d\n", p.Text, p.Code, len(ps)-i)
	}
	return b.Bytes()
}

func list(b *bytes.Buffer, key string, items []string) {
	if len(items) == 0 {
		fmt.Fprintf(b, "  %s: []\n", key)
		return
	}
	fmt.Fprintf(b, "  %s:\n", key)
	for _, it := range items {
		fmt.Fprintf(b, "    - %s\n", quote(it))
	}
}

// quote returns s as a YAML scalar: plain when safe, else single-quoted
// (which has no escapes except ” for a quote).
func quote(s string) string {
	if s != "" && !strings.ContainsAny(s, ":#{}[],&*!|>'\"%`") && !strings.ContainsAny(s[:1], "@-? ") && strings.TrimSpace(s) == s {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// Apply writes the generated files into userDir, replacing only files whose
// content changed. It reports whether anything changed, i.e. whether a
// deploy is needed.
func Apply(userDir string, s Settings) (changed bool, err error) {
	files, err := Compile(s)
	if err != nil {
		return false, err
	}
	for name, content := range files {
		path := filepath.Join(userDir, name)
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, content) {
			continue
		}
		if err := writeAtomic(path, content); err != nil {
			return changed, fmt.Errorf("settings: %w", err)
		}
		changed = true
	}
	return changed, nil
}
