// Command m0-rime is M0 spike 1 (DESIGN §10): drive librime from Go through
// purego with rime-ice data, and measure per-key latency and allocations.
//
// Default mode patches every lua_* component out of rime_ice and loads only
// the "default" librime modules. With -lua it uses rime-ice unmodified and
// loads the "plugins" module (Homebrew's librime-lua) once, to record the
// cost Shixin avoids.
//
// Spike code: throwaway, not part of the product.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"time"

	"shixin/internal/rime"
)

const noLuaPatch = `# Generated by spikes/m0-rime: rime-ice engine without any lua_* component.
patch:
  engine/processors:
    - ascii_composer
    - recognizer
    - key_binder
    - speller
    - punctuator
    - selector
    - navigator
    - express_editor
  engine/segmentors:
    - ascii_segmentor
    - matcher
    - abc_segmentor
    - affix_segmentor@radical_lookup
    - punct_segmentor
    - fallback_segmentor
  engine/translators:
    - punct_translator
    - script_translator
    - table_translator@custom_phrase
    - table_translator@melt_eng
    - table_translator@cn_en
    - table_translator@radical_lookup
  engine/filters:
    - reverse_lookup_filter@radical_reverse_lookup
    - simplifier@emoji
    - simplifier@traditionalize
    - uniquifier
`

const defaultPatch = `patch:
  schema_list:
    - schema: rime_ice
`

// A mix of short words, long sentences and English, typed as full pinyin and
// committed with space.
var corpus = []string{
	"nihao", "zhongguo", "woaini", "xiexie", "shurufa", "pinyin", "dajiahao",
	"jintiantianqizhenhao", "zhegewentihenfuza", "womenyiqiquchifanba",
	"xianzaijidianle", "zhonghuarenmingongheguo", "shixinshurufa",
	"diannao", "ruanjian", "kaifa", "xingneng", "kuaisu", "wenti", "jiejue",
	"hello", "world", "github", "rime", "ceshiyixia",
	"bujiandebuxiangjian", "yigeren", "ruguonixiangyao", "meiyouwenti",
}

func main() {
	libPath := flag.String("lib", "/opt/homebrew/opt/librime/lib/librime.1.dylib", "librime path")
	root := flag.String("root", ".", "repository root")
	withLua := flag.Bool("lua", false, "use rime-ice with Lua (comparison run)")
	iters := flag.Int("iters", 20, "corpus repetitions")
	flag.Parse()

	shared := filepath.Join(*root, "build/rime-data")
	variant := "nolua"
	modules := []string{"default"}
	if *withLua {
		variant = "lua"
		modules = []string{"default", "plugins"}
	}
	user := filepath.Join(*root, "build/spike", "user-"+variant)
	must(os.MkdirAll(user, 0o755))
	must(os.WriteFile(filepath.Join(user, "default.custom.yaml"), []byte(defaultPatch), 0o644))
	if *withLua {
		if _, err := os.Stat(filepath.Join(user, "lua")); err != nil {
			log.Fatalf("-lua needs rime-ice's lua/ in %s", user)
		}
	} else {
		must(os.WriteFile(filepath.Join(user, "rime_ice.custom.yaml"), []byte(noLuaPatch), 0o644))
	}
	logDir := filepath.Join(*root, "build/spike", "logs-"+variant)
	must(os.MkdirAll(logDir, 0o755))

	lib, err := rime.Load(*libPath)
	must(err)
	fmt.Printf("librime %s, variant=%s, modules=%v\n", lib.Version(), variant, modules)

	traits := rime.Traits{
		SharedDataDir:        shared,
		UserDataDir:          user,
		LogDir:               logDir,
		MinLogLevel:          1,
		DistributionName:     "Shixin",
		DistributionCodeName: "shixin",
		DistributionVersion:  "0.0.0-spike",
		AppName:              "rime.shixin",
		Modules:              modules,
	}
	lib.Setup(traits)
	lib.Initialize()

	t := time.Now()
	lib.StartMaintenance(false)
	lib.JoinMaintenanceThread()
	fmt.Printf("deploy (incremental check): %v\n", time.Since(t).Round(time.Millisecond))

	t = time.Now()
	s, err := lib.CreateSession()
	must(err)
	fmt.Printf("create_session (cold): %v\n", time.Since(t).Round(time.Microsecond))

	var (
		ctx    rime.Context
		st     rime.Status
		commit = make([]byte, 0, 256)
	)
	step := func(key int) {
		s.ProcessKey(key, 0)
		commit, _ = s.ReadCommit(commit)
		s.ReadContext(&ctx)
		s.ReadStatus(&st)
	}

	// Cold first key: dictionaries are not paged in yet.
	t = time.Now()
	step('n')
	fmt.Printf("first key (cold): %v\n", time.Since(t).Round(time.Microsecond))
	s.ClearComposition()

	// Correctness checks.
	show(s, &ctx, "nihao")
	show(s, &ctx, "shixinshurufa")
	show(s, &ctx, "rq") // date with Lua; plain pinyin without
	show(s, &ctx, "hello")

	// Warm-up pass, then the measured passes.
	for _, w := range corpus {
		for _, c := range w {
			step(int(c))
		}
		step(' ')
	}
	keys := 0
	for _, w := range corpus {
		keys += len(w) + 1
	}
	lat := make([]time.Duration, 0, keys**iters)
	var ms0, ms1 runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&ms0)
	for i := 0; i < *iters; i++ {
		for _, w := range corpus {
			for _, c := range w {
				t0 := time.Now()
				step(int(c))
				lat = append(lat, time.Since(t0))
			}
			t0 := time.Now()
			step(' ')
			lat = append(lat, time.Since(t0))
		}
	}
	runtime.ReadMemStats(&ms1)

	slices.Sort(lat)
	pct := func(p float64) time.Duration { return lat[min(len(lat)-1, int(p*float64(len(lat))))] }
	var sum time.Duration
	for _, d := range lat {
		sum += d
	}
	fmt.Printf("\nper key (process_key + get_commit + get_context + get_status), n=%d\n", len(lat))
	fmt.Printf("  mean %v  p50 %v  p90 %v  p99 %v  p99.9 %v  max %v\n",
		(sum / time.Duration(len(lat))).Round(time.Microsecond),
		pct(0.50).Round(time.Microsecond), pct(0.90).Round(time.Microsecond),
		pct(0.99).Round(time.Microsecond), pct(0.999).Round(time.Microsecond),
		lat[len(lat)-1].Round(time.Microsecond))
	fmt.Printf("  Go heap allocs per key: %.3f (latency slice preallocated)\n",
		float64(ms1.Mallocs-ms0.Mallocs)/float64(len(lat)))

	s.Destroy()
	lib.Finalize()
}

func show(s *rime.Session, ctx *rime.Context, input string) {
	s.ClearComposition()
	for _, c := range input {
		s.ProcessKey(int(c), 0)
	}
	s.ReadContext(ctx)
	var b strings.Builder
	for i, c := range ctx.Candidates {
		fmt.Fprintf(&b, " %d.%s", i+1, c.Text)
		if len(c.Comment) > 0 {
			fmt.Fprintf(&b, "(%s)", c.Comment)
		}
	}
	fmt.Printf("%-16s preedit=%q →%s\n", input, ctx.Preedit, b.String())
	s.ClearComposition()
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
